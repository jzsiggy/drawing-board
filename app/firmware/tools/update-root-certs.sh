#!/bin/sh
# Regenerates frame/root_certs.h from the macOS system trust store.
# Roots: Google Trust Services (Vercel, Supabase), GlobalSign (their
# cross-sign) and ISRG / Let's Encrypt (Vercel custom domains).
set -eu
cd "$(dirname "$0")/.."
KEYCHAIN=/System/Library/Keychains/SystemRootCertificates.keychain
OUT=frame/root_certs.h
{
  echo "// Generated by tools/update-root-certs.sh from the macOS trust store. Do not edit."
  echo "#pragma once"
  echo
  echo "static const char ROOT_CERTS[] ="
  for name in "GTS Root R1" "GTS Root R4" "GlobalSign Root CA" "ISRG Root X1" "ISRG Root X2"; do
    pem=$(security find-certificate -c "$name" -p "$KEYCHAIN")
    subject=$(printf '%s\n' "$pem" | openssl x509 -noout -subject -enddate | tr '\n' ' ')
    echo "    // $subject"
    printf '%s\n' "$pem" | sed 's/^/    "/; s/$/\\n"/'
  done
  echo "    ;"
} > "$OUT"
echo "Wrote $OUT"
